"""Write app/.streamlit/secrets.toml (git-ignored) from .env, using the read-only streamlit_ro user.

    python scripts/make_app_secrets.py
"""
from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "worker"))
from tracker.common import ROOT, env, load_env  # noqa: E402


def q(s: str | None) -> str:
    return '"' + (s or "").replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    load_env()
    out = ROOT / "app" / ".streamlit" / "secrets.toml"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(
        "# Generated by scripts/make_app_secrets.py — never commit\n"
        "[connections.tracker]\n"
        'dialect = "postgresql"\n'
        'driver = "psycopg2"\n'
        f"host = {q(env('SUPABASE_DB_HOST'))}\n"
        f"port = {int(env('SUPABASE_DB_PORT', '5432'))}\n"
        f"database = {q(env('SUPABASE_DB_NAME', 'postgres'))}\n"
        f"username = {q(env('SUPABASE_DB_USER_READER'))}\n"
        f"password = {q(env('SUPABASE_DB_PASSWORD_READER'))}\n"
        f"query = {{ sslmode = {q(env('SUPABASE_SSLMODE', 'require'))} }}\n",
        encoding="utf-8",
    )
    print(f"wrote {out.relative_to(ROOT)}")
